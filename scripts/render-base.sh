# Renders the HML Helm chart (code/deploy/hyperswitch/hml/chart in the main repository) into the Kustomize base of this tree:
#
#   apps/base/hyperswitch/            the chart with translator.enabled=false, one file per chart template
#   components/translator/            the four objects the translator adds (Deployment, Service, NetworkPolicy, Job db-init)
#
# The chart stays the source of truth for the services; this tree holds what Argo CD applies. Run it again after every chart
# change; `scripts/validate.sh` fails while the committed files differ from a fresh render.
#
#   bash 4on-k8s-infra/scripts/render-base.sh            rewrite the base and the component
#   bash 4on-k8s-infra/scripts/render-base.sh --check    render into a temporary directory and compare, write nothing
#
# Environment: HML_CHART (chart directory, default code/deploy/hyperswitch/hml/chart under the repository root),
# HML_CHART_VALUES (default values-hml.yaml of that chart). The tree sits next to code/ in the main repository checkout (4on-k8s-infra/).
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
TREE=$(cd "$HERE/.." && pwd)
ROOT=$(cd "$TREE/.." && pwd)
CHART=${HML_CHART:-$ROOT/code/deploy/hyperswitch/hml/chart}
VALUES=${HML_CHART_VALUES:-$CHART/values-hml.yaml}
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

command -v helm >/dev/null || { echo "FAILED   helm is not installed" >&2; exit 1; }
[ -f "$CHART/Chart.yaml" ] || { echo "FAILED   no chart at $CHART" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
helm template hyperswitch-hml "$CHART" --namespace hyperswitch -f "$VALUES" --set translator.enabled=false >"$WORK/core.yaml"
helm template hyperswitch-hml "$CHART" --namespace hyperswitch -f "$VALUES" --set translator.enabled=true >"$WORK/full.yaml"

OUT=$WORK/out
mkdir -p "$OUT/base" "$OUT/translator"
python3 -I - "$WORK/core.yaml" "$WORK/full.yaml" "$OUT" <<'PY'
import re, sys, collections

core_path, full_path, out = sys.argv[1:4]

def docs(path):
    """(kind, name, template file, text) of every object, in render order; the text is Helm's own, untouched."""
    result = []
    for d in re.split(r'^---\s*$', open(path).read(), flags=re.M):
        if not [l for l in d.splitlines() if l.strip() and not l.lstrip().startswith('#')]:
            continue  # a template that renders only its comment (db-init.yaml without the translator)
        kind = re.search(r'^kind: (\S+)', d, re.M)
        name = re.search(r'^metadata:\n(?:[ ]{2}\S.*\n)*?[ ]{2}name: (\S+)', d, re.M)
        src = re.search(r'^# Source: \S+?/templates/(\S+)', d, re.M)
        if not (kind and name and src):
            sys.exit('FAILED   an object of the render has no kind, name or source: ' + d[:80])
        result.append((kind.group(1), name.group(1), src.group(1), d.strip('\n') + '\n'))
    return result

core, full = docs(core_path), docs(full_path)
core_keys = {(k, n) for k, n, _, _ in core}
full_keys = {(k, n) for k, n, _, _ in full}
if core_keys - full_keys:
    sys.exit('FAILED   objects only without the translator: %s' % sorted(core_keys - full_keys))
core_text = {(k, n): t for k, n, _, t in core}
for k, n, _, t in full:
    if (k, n) in core_text and core_text[(k, n)] != t:
        sys.exit('FAILED   the translator changes %s %s: it must only add objects' % (k, n))

per_file = collections.OrderedDict()
for k, n, src, t in core:
    per_file.setdefault(src, []).append(t)
for src, items in per_file.items():
    open('%s/base/%s' % (out, src), 'w').write('---\n' + '---\n'.join(items))
open(out + '/base/kustomization.yaml', 'w').write(
    '# Generated by scripts/render-base.sh from the HML chart; do not edit, change the chart and render again.\n'
    'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n'
    + ''.join('  - %s\n' % f for f in sorted(per_file)))

added = [(k, n, s, t) for k, n, s, t in full if (k, n) not in core_text]
open(out + '/translator/translator.yaml', 'w').write('---\n' + '---\n'.join(t for _, _, _, t in added))
open(out + '/translator/kustomization.yaml', 'w').write(
    '# Generated by scripts/render-base.sh from the HML chart; do not edit, change the chart and render again.\n'
    'apiVersion: kustomize.config.k8s.io/v1alpha1\nkind: Component\nresources:\n  - translator.yaml\n')
print('rendered %d base objects in %d files, %d translator objects' % (len(core), len(per_file), len(added)))
PY

if [ "$CHECK" = 1 ]; then
  rc=0
  diff -r "$OUT/base" "$TREE/apps/base/hyperswitch" >"$WORK/base.diff" || rc=1
  diff -r "$OUT/translator" "$TREE/components/translator" >"$WORK/translator.diff" || rc=1
  if [ "$rc" = 0 ]; then echo "ok       the base and the translator component equal a fresh render of the chart"; exit 0; fi
  echo "FAILED   the committed base differs from a fresh render of the chart; run: bash 4on-k8s-infra/scripts/render-base.sh" >&2
  head -20 "$WORK/base.diff" "$WORK/translator.diff" >&2
  exit 1
fi

rm -f "$TREE"/apps/base/hyperswitch/*.yaml "$TREE"/components/translator/*.yaml
cp "$OUT"/base/*.yaml "$TREE/apps/base/hyperswitch/"
cp "$OUT"/translator/*.yaml "$TREE/components/translator/"
echo "ok       wrote apps/base/hyperswitch and components/translator"
